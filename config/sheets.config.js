export function getSheetId(cabang, tipe, bulan = BULAN_AKTIF) {
  const sheet = CABANG[cabang]?.sheets?.[bulan]?.[tipe];
  if (!sheet) throw new Error(`Sheet tidak ditemukan: ${cabang} / ${tipe} / ${bulan}`);
  return sheet;
}

export function getCabangInfo(cabang) {
  const info = CABANG[cabang];
  if (!info) throw new Error(`Cabang tidak valid: ${cabang}`);
  return info;
}

export function getAllCabang() {
  return Object.entries(CABANG).map(([key, val]) => ({
    key,
    nama: val.nama,
    hasKids: val.hasKids,
  }));
}

function getMiddleColumn(rangeStr) {
  const [start] = rangeStr.split(':');
  const m = start.match(/^([A-Z]+)(\d+)$/);
  if (!m) return start;
  const [, col, row] = m;
  const colNum = col.charCodeAt(0) - 64;
  const midCol = String.fromCharCode(64 + colNum + 1);
  return `${midCol}${row}`;
}

function resolveCabangKey(input) {
  const key = input?.toString().trim().toLowerCase();
  if (CABANG[key]) return key;
  const found = Object.entries(CABANG).find(
    ([, val]) => val.nama.toLowerCase() === key
  );
  return found ? found[0] : null;
}

export function getPeringkatId(namaCabang, bulan = BULAN_AKTIF) {
  const key = resolveCabangKey(namaCabang);
  if (!key) throw new Error(`Cabang tidak ditemukan: ${namaCabang}`);
  const id = CABANG[key].sheets?.[bulan]?.peringkat;
  if (!id) throw new Error(`Sheet peringkat belum dikonfigurasi: ${namaCabang} / ${bulan}`);
  return id;
}

export function getAllCabangPeringkat(bulan = BULAN_AKTIF) {
  return Object.entries(CABANG).map(([key, val]) => ({
    nama: val.nama.toLowerCase(),
    singkatan: key.toUpperCase(),
    id: val.sheets?.[bulan]?.peringkat || null,
    range: getMiddleColumn(val.peringkat.summaryRange),
  }));
}
